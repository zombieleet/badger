// img2bmp converts a PNG/JPEG into a 1-bit Go byte slice for drawBitmap.
// Runs on your PC (regular Go, not TinyGo):
//
//	go run ./tools/img2bmp -in gopher.png -name gopher -w 100 -h 120 -o internal/screen/gopher_bmp.go
//
// Usually invoked via `go generate ./internal/screen` (see internal/screen/gen.go).
package main

import (
	"flag"
	"fmt"
	"image"
	_ "image/jpeg"
	_ "image/png"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "", "input image (png or jpg)")
	name := flag.String("name", "img", "prefix for generated names (<name>W, <name>H, <name>Bmp)")
	outW := flag.Int("w", 0, "output width in px (0 = original)")
	outH := flag.Int("h", 0, "output height in px (0 = original)")
	thr := flag.Int("t", 128, "threshold 0-255: pixels darker than this become black")
	pkg := flag.String("pkg", "screen", "Go package name")
	outFile := flag.String("o", "", "output file (default: stdout)")
	flag.Parse()

	f, err := os.Open(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	img, _, err := image.Decode(f)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	b := img.Bounds()
	W, H := *outW, *outH
	if W == 0 {
		W = b.Dx()
	}
	if H == 0 {
		H = b.Dy()
	}

	stride := (W + 7) / 8
	data := make([]byte, stride*H)

	for y := 0; y < H; y++ {
		for x := 0; x < W; x++ {
			// nearest-neighbour scaling
			sx := b.Min.X + x*b.Dx()/W
			sy := b.Min.Y + y*b.Dy()/H
			r, g, bl, a := img.At(sx, sy).RGBA() // 16-bit channels
			if a < 0x8000 {
				continue // transparent → white
			}
			lum := ((299*r + 587*g + 114*bl) / 1000) >> 8 // 0-255
			if int(lum) < *thr {
				data[y*stride+x/8] |= 0x80 >> uint(x%8)
			}
		}
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by img2bmp from %s. DO NOT EDIT.\n\n", *in)
	fmt.Fprintf(&sb, "package %s\n\n", *pkg)
	fmt.Fprintf(&sb, "const %sW, %sH = %d, %d\n\n", *name, *name, W, H)
	fmt.Fprintf(&sb, "var %sBmp = []byte{", *name)
	for i, v := range data {
		if i%16 == 0 {
			sb.WriteString("\n\t")
		}
		fmt.Fprintf(&sb, "0x%02x, ", v)
	}
	sb.WriteString("\n}\n")

	if *outFile == "" {
		fmt.Print(sb.String())
		return
	}
	if err := os.WriteFile(*outFile, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
